const toGuiltDayNumber = (value) => {
  const normalized = String(value ?? '').replace(/[۰-۹]/g, digit => '۰۱۲۳۴۵۶۷۸۹'.indexOf(digit));
  const number = Number(normalized);
  return Number.isInteger(number) && number >= 1 && number <= 28 ? number : null;
};
const fa = value => String(value).replace(/[0-9]/g, digit => '۰۱۲۳۴۵۶۷۸۹'[Number(digit)]);
const intro = guide => 'راهنمای روز ' + fa(guide.day) + ' احساس گناه — ' + guide.title
  + '\n\nاین پاسخ فقط درباره مهارت همین روز است. گناه معمولاً به رفتار یا ترک فعل مشخص مربوط می‌شود؛ شرم حکم کلی درباره ارزش خود و خودسرزنشی می‌تواند نسبت‌دادن تقصیر فراتر از شواهد باشد. احساس گناه به‌تنهایی ثابت نمی‌کند که مسئولیتی متوجه توست؛ واقعیت، اختیار، آگاهی، فشار یا اجبار و سهم دیگران باید جداگانه دیده شوند.';

export function getGuiltDailyAssistantPromptGroups(day) {
  const n = toGuiltDayNumber(day);
  const guide = GUILT_DAILY_ASSISTANT_GUIDES.find(item => item.day === n);
  if (!guide) return [];
  return [
    { label: 'فهم تمرین روز ' + fa(guide.day), questions: guide.questions.filter(q => ['exercise_meaning', 'exercise_example'].includes(q.kind)) },
    { label: 'فهم اقدام اختصاصی روز ' + fa(guide.day), questions: guide.questions.filter(q => ['action_meaning', 'action_example'].includes(q.kind)) },
    { label: 'تفاوت تمرین و اقدام', questions: guide.questions.filter(q => q.kind === 'exercise_action_difference') },
    { label: 'اجرا و موانع', questions: guide.questions.filter(q => ['light_version', 'not_done', 'no_event', 'can_change', 'duration'].includes(q.kind)) },
    { label: 'ارزیابی و ایمنی', questions: guide.questions.filter(q => ['guilt_increased', 'talk_other', 'success', 'stop'].includes(q.kind)) },
  ];
}

