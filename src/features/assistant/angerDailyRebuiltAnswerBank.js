/**
 * Rebuilt T01 anger guide responses.
 * Each answer is composed from the current day's own exercise, action,
 * examples, success and safety criteria. The previous prepared-answer bank
 * is deliberately not used by this response path.
 */
const clean = (value, fallback = '') => String(value || fallback).trim();
const paragraph = (...parts) => parts.filter(Boolean).join('\n\n');

function answerBody({ guide, question, plainSteps = {} }) {
  const day = guide.day;
  const exercise = clean(guide.exercise);
  const action = clean(guide.action);
  const exerciseExample = clean(guide.exerciseExample, 'یک نمونه ساده و کم‌فشار از تجربه روزمره‌ات را انتخاب کن و فقط همان بخش‌هایی را که در تمرین آمده ثبت کن.');
  const actionExample = clean(guide.actionExample, 'در یک موقعیت امن، همان رفتار کوچک و مشخصی را که در اقدام امروز آمده انجام بده؛ اگر امن نیست، اجرا نکن.');
  const light = clean(guide.lightVersion, 'فقط بخش کوتاه و امن تمرین را انجام بده.');
  const success = clean(guide.successCriterion, 'بتوانی مهارت امروز را در یک نمونه روشن تشخیص بدهی.');
  const stop = clean(guide.stopCondition, 'اگر فشار روانی یا احتمال آسیب بیشتر شد، تمرین را متوقف کن.');
  const rest = clean(guide.restVersion, 'امروز تمرین را کنار بگذار و در زمان مناسب‌تری به آن برگرد.');
  const progress = clean(guide.progressVersion, 'اگر این مهارت را قبلاً در شرایط امن به کار برده‌ای، فقط همان پیشرفت را ثبت کن؛ موقعیت دشوارتر نساز.');
  const objective = clean(guide.objective);
  const skill = clean(guide.skill);
  const mechanism = clean(guide.mechanism);
  const reflection = clean(guide.reflectionQuestion);
  const humanSupport = clean(guide.whenToSeekHumanSupport);

  switch (question.kind) {
    case 'exercise_meaning':
      return paragraph(
        `در روز ${day}، تمرین تو بر مهارت «${guide.title}» متمرکز است. به‌جای اینکه فقط درباره خشم فکر کنی، این مهارت را در یک نمونه روشن بررسی می‌کنی. هدف این روز این است: ${objective}`,
        skill && `مهارتی که امروز تقویتش می‌کنی این است: ${skill}`,
        mechanism,
        `برای انجامش این مسیر را قدم‌به‌قدم برو: ${exercise}`,
        clean(plainSteps.exercise),
        'تمرین را به‌ترتیب پیش ببر و فقط همان مواردی را ثبت کن که در دستور تمرین آمده است. تعداد نمونه‌ها را هم بیشتر یا کمتر نکن. نوشته‌ات لازم نیست طولانی یا بی‌نقص باشد؛ کافی است مشاهده واقعی را از حدس، قضاوت و موارد نامعلوم جدا کنی.'
      );
    case 'exercise_example':
      return paragraph(
        `برای ملموس‌تر شدن تمرین روز ${day} با عنوان «${guide.title}»، این موقعیت فرضی را در نظر بگیر:`,
        exerciseExample,
        `حالا همین منطق را روی یک نمونه کم‌فشار از زندگی خودت امتحان کن. اگر موقعیتت دقیقاً شبیه این مثال نیست، اشکالی ندارد؛ بخش مهم تمرین همان است: ${objective}`,
        'این فقط یک مثال برای فهمیدن روش است؛ لازم نیست عمداً چنین موقعیتی ایجاد کنی یا خودت را وارد بحث کنی.'
      );
    case 'action_meaning':
      return paragraph(
        `اقدام اختصاصی امروز، آموخته تمرین را به یک رفتار کوچک و عملی پیوند می‌دهد. در روز ${day} می‌توانی مهارت «${guide.title}» را به این شکل در انتخاب‌های روزمره به کار بگیری:`,
        skill && `این اقدام به تمرین مهارت «${skill}» کمک می‌کند؛ نه اینکه مجبور باشی احساس خشم را پنهان کنی.`,
        action,
        clean(plainSteps.action),
        'تمرین به تو فرصت می‌دهد موضوع را بررسی کنی؛ اقدام یعنی اگر موقعیت مناسب و امنی پیش آمد، یک رفتار مشخص را انتخاب کنی. انجام اقدام اجباری نیست و قرار نیست برای انجامش موقعیت بسازی.'
      );
    case 'action_example':
      return paragraph(
        `یک نمونه فرضی از اقدام روز ${day} را ببین. هدف این مثال فقط روشن‌کردن شیوه انجام اقدام امروز است:`,
        actionExample,
        `در مثال، به‌جای واکنش عجولانه، روی همان مهارت امروز یعنی «${guide.title}» تکیه می‌کنی. اگر شرایط تو متفاوت است، اصل اقدام را نگه دار و شکل امن و متناسب با شرایط خودت را انتخاب کن.`,
        'اگر شرایط زندگی تو شبیه این نمونه نیست یا گفتن یا انجام‌دادن آن امن نیست، آن را اجرا نکن؛ اقدام امروز فقط در موقعیت امن و با رضایت آزادانه مطرح است. اگر احتمال خطر هست، فاصله امن ایجاد کن و کمک بگیر.'
      );
    case 'light_version':
      return paragraph(
        'اگر نسخه کامل تمرین با توان یا شرایط امروزت سازگار نیست، خودت را تحت فشار نگذار. نسخه سبک کمک می‌کند با فشار کمتر ارتباطت را با مسیر حفظ کنی؛ این انتخاب نشانه شکست نیست.',
        `نسخه سبک مخصوص روز ${day} این است: ${light}`,
        `اگر آمادگی بیشتری داری، فقط در حدی که امن و طبیعی است می‌توانی این گام را هم در نظر بگیری: ${progress}`,
        `و اگر امروز زمان یا آمادگی نداری: ${rest}`
      );
    case 'success':
      return paragraph(
        `برای سنجش تمرین روز ${day}، به‌جای انتظار برای تغییر بزرگ یا ازبین‌رفتن خشم، این معیار روشن را بررسی کن: ${success}`,
        `به زبان ساده، اگر توانستی بخش اصلی تمرین «${guide.title}» را در یک نمونه تشخیص بدهی یا ثبت کنی، به اندازه لازم پیش رفته‌ای. لازم نیست احساس خشم کاملاً کم شود یا رفتار دیگران تغییر کند.`,
        reflection && `برای مرور کوتاه از خودت بپرس: ${reflection}`,
        'اگر بخشی مبهم مانده، همان قسمت را دوباره با یک مثال ساده بررسی کن؛ خودت را بابت کامل‌نبودن سرزنش نکن.'
      );
    case 'stop':
      return paragraph(
        'هر نشانه‌ای از به‌خطر‌افتادن امنیت یا بدترشدن حال روانی، دلیل کافی برای توقف است. لازم نیست تمرین را به پایان برسانی؛ سلامت و امنیت تو در اولویت است.',
        `برای روز ${day} به این محدودیت توجه کن: ${stop}`,
        'اگر احساس می‌کنی ممکن است به خودت، فرد دیگری یا اموال آسیب برسد، فاصله امن ایجاد کن؛ از موقعیت دور شو، ابزار یا وسیله خطرناک را کنار بگذار و از فرد قابل اعتماد یا خدمات اضطراری محل زندگی کمک فوری بخواه. در وضعیت خطر، تمرین نوشتاری را ادامه نده.'
      );
    case 'no_event':
      return paragraph(
        `اگر امروز موقعیتی برای تمرین «${guide.title}» پیش نیامده، نه منتظر اتفاق ناخوشایند بمان و نه عمداً بحثی ایجاد کن. همین نبودن موقعیت را ثبت کن؛ لازم نیست برای انجام تمرین اتفاقی بسازی.`,
        `اگر مرور یک تجربه قبلی برایت امن و قابل‌تحمل است، می‌توانی از یک نمونه کم‌فشار قبلی استفاده کنی؛ در غیر این صورت نسخه استراحت امروز را انتخاب کن: ${rest}`,
        `اگر فقط می‌خواهی ارتباطت با مسیر حفظ شود، همین نسخه کوتاه کافی است: ${light}`
      );
    case 'exercise_action_difference':
      return paragraph(
        `در برنامه روز ${day}، تمرین و اقدام دو بخش مرتبط با کارکردهای جداگانه‌اند. تمرین امروز چنین است: ${exercise}`,
        `اقدام اختصاصی امروز این است: ${action}`,
        `تمرین به شناخت و مشاهده مهارت «${guide.title}» کمک می‌کند؛ اقدام، انتخاب رفتاری کوچک در یک موقعیت واقعی و امن است. بنابراین ممکن است تمرین را انجام بدهی، اما در همان روز فرصتی مناسب برای اقدام پیدا نشود. این موضوع طبیعی است و نیازی به ساختن موقعیت ندارد.`
      );
    case 'not_done':
      return paragraph(
        'انجام‌نشدن تمرین به معنی شکست نیست. خودت را سرزنش نکن و برای جبران یک روز، چند روز را یک‌جا انجام نده؛ هر زمان آماده بودی از همین مرحله ادامه بده.',
        `اگر کمبود وقت یا دشواری تمرین مانع شده، می‌توانی با نسخه کوتاه روز ${day} شروع کنی: ${light}`,
        `اگر موقعیت مناسبی وجود نداشته یا شرایط امن نبوده، فعلاً این گزینه را انتخاب کن: ${rest}`,
        'وقتی آماده بودی، به مسیر عادی برگرد. هدف، یادگیری تدریجی است نه انجام بی‌وقفه و اجباری همه تمرین‌ها.'
      );
    case 'anger_increased':
      return paragraph(
        'اگر در جریان تمرین، خشم یا آشفتگی بیشتر شد، همان لحظه مکث کن و تمرین را کنار بگذار. برای یادگیری مهارت امروز لازم نیست ناراحتی را تحمل کنی.',
        `محدودیت ویژه روز ${day} این است: ${stop}`,
        humanSupport,
        'اگر امن است از موقعیت تنش‌زا فاصله بگیر، نوشتن یا گفت‌وگو را کنار بگذار و به یک کار خنثی و آرام برگرد. اگر احتمال آسیب به خودت یا دیگری وجود دارد، تنها نمان و فوراً از فرد قابل اعتماد یا خدمات اضطراری محل زندگی کمک بگیر.',
        'بعداً فقط در صورت احساس امنیت و آمادگی تصمیم بگیر که تمرین را به شکل سبک‌تر ادامه بدهی یا فعلاً کنار بگذاری.'
      );
    case 'talk_other':
      return paragraph(
        `برای انجام تمرین روز ${day}، گفت‌وگو با فرد دیگری الزامی نیست. بخش اصلی را می‌توانی به‌تنهایی و در فضای خصوصی انجام بدهی: ${exercise}`,
        'اگر اقدام امروز به تعامل با شخص دیگری مربوط می‌شود، فقط وقتی آن را در نظر بگیر که هر دو نفر آزادانه رضایت داشته باشند، بتوانند مخالفت کنند و بدون ترس گفت‌وگو را متوقف کنند.',
        'اگر تهدید، خشونت، ترس یا احتمال تلافی وجود دارد، گفت‌وگوی مستقیم یا میانجی‌گری مشترک را به خودت تحمیل نکن. فاصله امن و حمایت مستقل مهم‌تر است.'
      );
    case 'can_change':
      return paragraph(
        `بله؛ شیوه اجرای تمرین روز ${day} می‌تواند با شرایط تو هماهنگ شود، به شرط آنکه هدف اصلی یعنی تمرین مهارت «${guide.title}» حفظ شود.`,
        `نسخه کوتاه‌تر و ساده‌ترش این است: ${light}`,
        `اگر لازم است زمان یا شیوه ثبت را عوض کنی، اشکالی ندارد؛ اما این بخش اصلی را حذف نکن: ${objective}`,
        'هیچ تغییری نباید تو را مجبور کند وارد موقعیت ناامن شوی، با کسی روبه‌رو شوی یا چیزی را که نمی‌خواهی افشا کنی.'
      );
    case 'duration':
      return paragraph(
        `در راهنمای روز ${day} زمان ثابتی برای این تمرین تعیین نشده است؛ بنابراین بهتر است عددی نسازیم یا تو را به مدت‌زمانی ساختگی متعهد نکنیم.`,
        `به‌اندازه‌ای ادامه بده که بخش اصلی «${guide.title}» را بفهمی و انجام دهی. اگر وقت یا تمرکز کافی نداری، نسخه سبک همین روز را انتخاب کن: ${light}`,
        'هر وقت خسته شدی می‌توانی مکث کنی. کیفیت فهم و رعایت ایمنی مهم‌تر از مدت‌زمان یا کامل‌کردن همه جزئیات است.'
      );
    default:
      return null;
  }
}

export function buildAngerDailyRebuiltAnswer({ guide, question, plainSteps } = {}) {
  if (!guide || guide.topicId !== 'T01' || !question) return null;
  const body = answerBody({ guide, question, plainSteps });
  if (!body) return null;
  // The transcript already displays the user's question and the assistant icon.
  // Keep this message limited to the answer body; do not repeat labels or daily summaries.
  return body;
}
