import { appendDailyAssistantSafetyReminder } from './dailyAssistantSafetyReminder.js';

/**
 * Rebuilt T01 anger guide responses.
 * Each answer is composed from the current day's own exercise, action,
 * examples, success and safety criteria. The previous prepared-answer bank
 * is deliberately not used by this response path.
 */
const clean = (value, fallback = '') => String(value || fallback).trim();
const paragraph = (...parts) => parts.filter(Boolean).join('\n\n');

function answerBody({ guide, question }) {
  const day = guide.day;
  const exercise = clean(guide.exercise);
  const action = clean(guide.action);
  const exerciseExample = clean(guide.exerciseExample, 'یک نمونه ساده و کم‌فشار از تجربه روزمره‌ات را انتخاب کن و فقط همان بخش‌هایی را که در تمرین آمده ثبت کن.');
  const actionExample = clean(guide.actionExample, 'در یک موقعیت امن، همان رفتار کوچک و مشخصی را که در اقدام امروز آمده انجام بده؛ اگر امن نیست، اجرا نکن.');
  const light = clean(guide.lightVersion, 'فقط بخش کوتاه و امن تمرین را انجام بده.');
  const success = clean(guide.successCriterion, 'بتوانی مهارت امروز را در یک نمونه روشن تشخیص بدهی.');
  const stop = clean(guide.stopCondition, 'اگر فشار روانی یا احتمال آسیب بیشتر شد، تمرین را متوقف کن.');
  const rest = clean(guide.restVersion, 'امروز تمرین را کنار بگذار و در زمان مناسب‌تری به آن برگرد.');
  const progress = clean(guide.progressVersion, 'اگر این مهارت را قبلاً در شرایط امن به کار برده‌ای، فقط همان پیشرفت را ثبت کن؛ موقعیت دشوارتر نساز.');
  const objective = clean(guide.objective);

  switch (question.kind) {
    case 'exercise_meaning':
      return paragraph(
        `آره عزیزم. در روز ${day} قرار نیست فقط درباره خشم فکر کنی؛ می‌خواهیم مهارت «${guide.title}» را در یک نمونه روشن تمرین کنی. این کار کمک می‌کند ${objective.charAt(0).toLocaleLowerCase('fa') + objective.slice(1)}`,
        `برای انجامش این مسیر را برو: ${exercise}`,
        'هدف امروز روشن است: تمرین را قدم‌به‌قدم انجام بده و همان بخش‌هایی را ثبت کن که خود متن تمرین خواسته است. تعداد نمونه‌ها را همان‌طور که خود متن تمرین خواسته نگه دار؛ لازم نیست نوشته‌ات طولانی یا بی‌نقص باشد. مهم این است که چیزی را که واقعاً مشاهده کرده‌ای از حدس، قضاوت یا چیزی که هنوز نمی‌دانی جدا نگه داری.'
      );
    case 'exercise_example':
      return paragraph(
        `حتماً عزیزم. برای اینکه تمرین روز ${day} یعنی «${guide.title}» ملموس‌تر شود، این موقعیت فرضی را ببین:`,
        exerciseExample,
        `حالا همین منطق را روی یک نمونه کم‌فشار از زندگی خودت امتحان کن. اگر موقعیتت دقیقاً شبیه این مثال نیست، اشکالی ندارد؛ بخش مهم تمرین همان است: ${objective}`,
        'این فقط یک مثال برای فهمیدن روش است؛ لازم نیست عمداً چنین موقعیتی ایجاد کنی یا خودت را وارد بحث کنی.'
      );
    case 'action_meaning':
      return paragraph(
        `اقدام اختصاصی امروز، یک قدم رفتاری کوچک در کنار تمرین نوشتاری است. در روز ${day} قرار است مهارت «${guide.title}» را به این شکل وارد انتخاب‌های روزمره‌ات کنی:`,
        action,
        'تمرین به تو فرصت می‌دهد موضوع را بررسی کنی؛ اقدام یعنی اگر موقعیت مناسب و امنی پیش آمد، یک رفتار مشخص را انتخاب کنی. انجام اقدام اجباری نیست و قرار نیست برای انجامش موقعیت بسازی.'
      );
    case 'action_example':
      return paragraph(
        `بله عزیزم؛ یک نمونه فرضی از اقدام روز ${day} این است:`,
        actionExample,
        `در مثال، به‌جای واکنش عجولانه، روی همان مهارت امروز یعنی «${guide.title}» تکیه می‌کنی. اگر شرایط تو متفاوت است، اصل اقدام را نگه دار و شکل امن و متناسب با شرایط خودت را انتخاب کن.`,
        'اگر شرایط زندگی تو شبیه این نمونه نیست یا گفتن یا انجام‌دادن آن امن نیست، آن را اجرا نکن؛ اقدام امروز فقط در موقعیت امن و با رضایت آزادانه مطرح است. اگر احتمال خطر هست، فاصله امن ایجاد کن و کمک بگیر.'
      );
    case 'light_version':
      return paragraph(
        'اگر نسخه کامل امروز برایت سنگین است، خودت را مجبور نکن. انتخاب نسخه سبک شکست محسوب نمی‌شود؛ فقط حجم کار را با توان و شرایط امروزت هماهنگ می‌کنی.',
        `نسخه سبک مخصوص روز ${day} این است: ${light}`,
        `اگر آمادگی بیشتری داری، فقط در حدی که امن و طبیعی است می‌توانی این گام را هم در نظر بگیری: ${progress}`,
        `و اگر امروز زمان یا آمادگی نداری: ${rest}`
      );
    case 'success':
      return paragraph(
        `برای فهمیدن اینکه تمرین روز ${day} را درست انجام داده‌ای، دنبال نتیجه خارق‌العاده یا ازبین‌رفتن خشم نگرد. معیار امروز این است: ${success}`,
        `به زبان ساده، اگر توانستی بخش اصلی تمرین «${guide.title}» را در یک نمونه تشخیص بدهی یا ثبت کنی، به اندازه لازم پیش رفته‌ای. لازم نیست احساس خشم کاملاً کم شود یا رفتار دیگران تغییر کند.`,
        'اگر بخشی مبهم مانده، همان قسمت را دوباره با یک مثال ساده بررسی کن؛ خودت را بابت کامل‌نبودن سرزنش نکن.'
      );
    case 'stop':
      return paragraph(
        'هر وقت ادامه تمرین امنیت یا حال تو را به خطر می‌اندازد، همان‌جا توقف کن. تمام‌کردن تمرین از سلامت تو مهم‌تر نیست.',
        `برای روز ${day} به این محدودیت توجه کن: ${stop}`,
        'اگر احساس می‌کنی ممکن است به خودت، فرد دیگری یا اموال آسیب برسد، از موقعیت فاصله امن بگیر، ابزار یا وسیله خطرناک را کنار بگذار و از فرد قابل اعتماد یا خدمات اضطراری محل زندگی کمک فوری بخواه. در وضعیت خطر، تمرین نوشتاری را ادامه نده.'
      );
    case 'no_event':
      return paragraph(
        `اگر امروز نمونه‌ای برای تمرین «${guide.title}» پیش نیامده، لازم نیست منتظر اتفاق ناخوشایند بمانی یا خودت موقعیت خشم‌آور بسازی. نبودن نمونه هم بخشی از واقعیت امروز توست.`,
        `اگر مرور یک تجربه قبلی برایت امن و قابل‌تحمل است، می‌توانی از یک نمونه ساده و قدیمی استفاده کنی؛ در غیر این صورت نسخه استراحت امروز را انتخاب کن: ${rest}`,
        `اگر فقط می‌خواهی ارتباطت با مسیر حفظ شود، همین نسخه کوتاه کافی است: ${light}`
      );
    case 'exercise_action_difference':
      return paragraph(
        `در روز ${day}، تمرین و اقدام دو کار مرتبط اما متفاوت‌اند. تمرین امروز این است: ${exercise}`,
        `اقدام اختصاصی امروز این است: ${action}`,
        `پس تمرین، بخش یادگیری و مشاهده مهارت «${guide.title}» است؛ اقدام، انتخاب یک رفتار کوچک در موقعیت واقعی و امن است. ممکن است تمرین را انجام بدهی اما امروز موقعیت مناسبی برای اقدام پیش نیاید؛ این کاملاً قابل قبول است.`
      );
    case 'not_done':
      return paragraph(
        'اشکالی ندارد عزیزم؛ قرار نیست بابت یک روز انجام‌ندادن، خودت را سرزنش کنی یا چند روز را یک‌جا جبران کنی. از همان نقطه‌ای که هستی ادامه می‌دهیم.',
        `اگر دلیلش کمبود وقت یا دشواری تمرین بوده، کوچک‌ترین شروع برای روز ${day} این است: ${light}`,
        `اگر دلیلش نبود موقعیت یا مناسب‌نبودن شرایط بوده، از این نسخه استفاده کن: ${rest}`,
        'وقتی آماده بودی، به مسیر عادی برگرد. هدف، یادگیری تدریجی است نه انجام بی‌وقفه و اجباری همه تمرین‌ها.'
      );
    case 'anger_increased':
      return paragraph(
        'اگر هنگام تمرین خشم، آشفتگی یا فشار روانی بیشتر شد، همین حالا تمرین را متوقف کن. لازم نیست برای فهمیدن درس امروز ناراحتی‌ات را تحمل کنی.',
        `محدودیت ویژه روز ${day} این است: ${stop}`,
        'اگر امن است از موقعیت تنش‌زا فاصله بگیر، نوشتن یا گفت‌وگو را کنار بگذار و به یک کار خنثی و آرام برگرد. اگر احتمال آسیب به خودت یا دیگری وجود دارد، تنها نمان و فوراً از فرد قابل اعتماد یا خدمات اضطراری محل زندگی کمک بگیر.',
        'بعداً فقط در صورت احساس امنیت و آمادگی تصمیم بگیر که تمرین را به شکل سبک‌تر ادامه بدهی یا فعلاً کنار بگذاری.'
      );
    case 'talk_other':
      return paragraph(
        `نه عزیزم؛ برای انجام تمرین روز ${day} لازم نیست حتماً با فرد دیگری صحبت کنی. بخش اصلی آن را می‌توانی به‌تنهایی و در فضای خصوصی انجام بدهی: ${exercise}`,
        'اگر اقدام امروز به تعامل با شخص دیگری مربوط می‌شود، فقط وقتی آن را در نظر بگیر که هر دو نفر آزادانه رضایت داشته باشند، بتوانند مخالفت کنند و بدون ترس گفت‌وگو را متوقف کنند.',
        'اگر تهدید، خشونت، ترس یا احتمال تلافی وجود دارد، گفت‌وگوی مستقیم یا میانجی‌گری مشترک را به خودت تحمیل نکن. فاصله امن و حمایت مستقل مهم‌تر است.'
      );
    case 'can_change':
      return paragraph(
        `بله، می‌توانی شکل انجام تمرین روز ${day} را با شرایطت هماهنگ کنی؛ فقط مهارت اصلی یعنی «${guide.title}» را حفظ کن.`,
        `نسخه کوتاه‌تر و ساده‌ترش این است: ${light}`,
        `اگر لازم است زمان یا شیوه ثبت را عوض کنی، اشکالی ندارد؛ اما این بخش اصلی را حذف نکن: ${objective}`,
        'هیچ تغییری نباید تو را مجبور کند وارد موقعیت ناامن شوی، با کسی روبه‌رو شوی یا چیزی را که نمی‌خواهی افشا کنی.'
      );
    case 'duration':
      return paragraph(
        `برای تمرین روز ${day} مدت زمان مشخصی ثبت نشده و زمان استاندارد یا عدد مشخصی در راهنمای این روز تعیین نشده؛ بنابراین نمی‌خواهم عددی حدس بزنم یا تو را به زمان ساختگی متعهد کنم.`,
        `به‌اندازه‌ای پیش برو که بخش اصلی «${guide.title}» را بفهمی و انجام بدهی. اگر امروز وقت یا تمرکزت کم است، نسخه سبک را انتخاب کن: ${light}`,
        'هر وقت خسته شدی می‌توانی مکث کنی. کیفیت فهم و رعایت ایمنی مهم‌تر از مدت‌زمان یا کامل‌کردن همه جزئیات است.'
      );
    default:
      return null;
  }
}

export function buildAngerDailyRebuiltAnswer({ guide, question } = {}) {
  if (!guide || guide.topicId !== 'T01' || !question) return null;
  const body = answerBody({ guide, question });
  if (!body) return null;
  const rendered = [
    '**دستیار هوشمند مسیر ۲۸**',
    `موضوع: خشم | روز ${guide.day}`,
    `**${clean(question.label || question.value)}**`,
    '**توضیح و راهنمای امروز**',
    '---',
    body,
    `**جمع‌بندی امروز**\nدر روز ${guide.day} قرار نیست با خشم بجنگی؛ قرار است مهارت «${guide.title}» را در حدی که امن و شدنی است تمرین کنی.`,
  ].join('\n\n');
  return appendDailyAssistantSafetyReminder(rendered, question.kind);
}
