export function toGriefDayNumber(value) {
  const n = Number(String(value ?? '').replace(/[۰-۹]/g, d => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d))));
  return Number.isInteger(n) && n >= 1 && n <= 28 ? n : null;
}

export function getGriefDailyAssistantPromptGroups(day) {
  const n = toGriefDayNumber(day);
  const g = GRIEF_DAILY_ASSISTANT_GUIDES.find(x => x.day === n);
  if (!g) return [];
  return [
    { label: 'فهم تمرین روز ' + g.day, questions: g.questions.filter(q => ['exercise_meaning', 'exercise_example'].includes(q.kind)) },
    { label: 'فهم اقدام اختصاصی روز ' + g.day, questions: g.questions.filter(q => ['action_meaning', 'action_example'].includes(q.kind)) },
    { label: 'تفاوت تمرین و اقدام', questions: g.questions.filter(q => q.kind === 'exercise_action_difference') },
    { label: 'اجرا و موانع', questions: g.questions.filter(q => ['light_version', 'not_done', 'no_event', 'can_change', 'duration'].includes(q.kind)) },
    { label: 'ارزیابی و ایمنی', questions: g.questions.filter(q => ['grief_increased', 'talk_other', 'success', 'stop'].includes(q.kind)) },
  ];
}

