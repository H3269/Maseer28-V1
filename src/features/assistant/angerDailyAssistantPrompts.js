export const ANGER_DAILY_ASSISTANT_GUIDES = Object.freeze(RAW_ANGER_DAILY_ASSISTANT_GUIDES.map(normalizeDailyAssistantGuide));

function toAngerDayNumber(value) {
  const normalized = String(value ?? '').replace(/[۰-۹]/g, (digit) => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(digit)));
  const parsed = Number(normalized);
  return Number.isInteger(parsed) ? parsed : NaN;
}

export function getAngerDailyAssistantPromptGroups(day) {
  const dayNumber = toAngerDayNumber(day);
  const guide = ANGER_DAILY_ASSISTANT_GUIDES.find((item) => item.day === dayNumber);
  if (!guide) return [];
  return [
    { label: 'فهم تمرین روز ' + guide.day, questions: guide.questions.filter((item) => ['exercise_meaning','exercise_example'].includes(item.kind)) },
    { label: 'فهم اقدام اختصاصی روز ' + guide.day, questions: guide.questions.filter((item) => item.kind.startsWith('action_')) },
    { label: 'تفاوت تمرین و اقدام', questions: guide.questions.filter((item) => item.kind === 'exercise_action_difference') },
    { label: 'اجرا و موانع', questions: guide.questions.filter((item) => ['light_version','not_done','no_event','can_change','duration'].includes(item.kind)) },
    { label: 'ارزیابی و ایمنی', questions: guide.questions.filter((item) => ['anger_increased','talk_other','success','stop'].includes(item.kind)) },
  ];
}

