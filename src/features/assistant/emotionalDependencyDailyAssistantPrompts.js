export function getEmotionalDependencyDailyAssistantPromptGroups(day) {
  const n = toDayNumber(day);
  const g = EMOTIONAL_DEPENDENCY_DAILY_ASSISTANT_GUIDES.find((item) => item.day === n);
  if (!g) return [];
  return [
    { label: 'فهم تمرین روز ' + fa(g.day), questions: g.questions.filter((q) => ['exercise_meaning', 'exercise_example'].includes(q.kind)) },
    { label: 'فهم اقدام اختصاصی روز ' + fa(g.day), questions: g.questions.filter((q) => ['action_meaning', 'action_example'].includes(q.kind)) },
    { label: 'تفاوت تمرین و اقدام', questions: g.questions.filter((q) => q.kind === 'exercise_action_difference') },
    { label: 'اجرا و موانع', questions: g.questions.filter((q) => ['light_version', 'not_done', 'no_event', 'can_change', 'duration'].includes(q.kind)) },
    { label: 'ارزیابی و ایمنی', questions: g.questions.filter((q) => ['dependency_increased', 'talk_other', 'success', 'stop'].includes(q.kind)) },
  ];
}

